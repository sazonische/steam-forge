#!/usr/bin/env bash
# Runs inside quay.io/pypa/manylinux_2_28_x86_64 (AlmaLinux 8, glibc 2.28).
set -euo pipefail

dnf install -y --setopt=install_weak_deps=False \
	zip \
	unzip \
	tar \
	pkgconf-pkg-config \
	autoconf \
	automake \
	libtool \
	autoconf-archive \
	perl-IPC-Cmd \
	perl-Time-Piece \
	perl-open \
	libX11-devel \
	libXext-devel \
	libXi-devel \
	libXrender-devel \
	libxcb-devel \
	xcb-util-devel \
	xcb-util-cursor-devel \
	xcb-util-image-devel \
	xcb-util-keysyms-devel \
	xcb-util-renderutil-devel \
	xcb-util-wm-devel \
	libxkbcommon-devel \
	libxkbcommon-x11-devel

dnf clean all

# AlmaLinux 8 ships Ninja 1.8, which cannot build the multi-output rules generated by current CMake.
PIPX_HOME=/opt/_internal/pipx PIPX_BIN_DIR=/usr/local/bin pipx install ninja==1.13.2
ninja --version
